struct Node {
    int data;   // ???????? ????????
    Node* prev; // ????????? ?? ?????????? ???????
    Node* next; // ????????? ?? ????????? ???????
};

// ???????? ??????? ? ????? ??????
void addToEnd(Node*& head, Node*& tail, int value) {
    Node* newNode = new Node;
    newNode->data = value;
    newNode->next = nullptr;
    newNode->prev = tail;

    // ???? ?????? ?? ?????? — ????????? ? ?????????? ???????
    if (tail != nullptr)
        tail->next = newNode;
    else
        head = newNode; // ?????? ??? ????

    tail = newNode; // ????? ??????? ?????????? ???????
}

// ??????? ??????? ?? ????????
bool removeByValue(Node*& head, Node*& tail, int value) {
    Node* cur = head;

    // ????? ????????
    while (cur != nullptr) {
        if (cur->data == value) {

            // ????????????? ?????????? ???????? ?????????
            if (cur->prev)
                cur->prev->next = cur->next;
            else
                head = cur->next;

            if (cur->next)
                cur->next->prev = cur->prev;
            else
                tail = cur->prev;

            delete cur; // ??????????? ??????
            return true;
        }

        cur = cur->next;
    }

    return false; // ??????? ?? ??????
}

// ??????? ??????
void printList(Node* head) {

    if (head == nullptr) {
        cout << "List is empty" << endl;
        return;
    }

    Node* cur = head;

    while (cur != nullptr) {
        cout << cur->data;

        if (cur->next)
            cout << " <-> ";

        cur = cur->next;
    }

    cout << endl;
}

// ?????????? ?????? ??????
void freeList(Node*& head, Node*& tail) {

    while (head != nullptr) {
        Node* tmp = head;
        head = head->next;
        delete tmp;
    }

    tail = nullptr;
}

